#!/usr/bin/env node
// Bakes the Outfit webfont into @font-face rules with data: URLs.
//
// Why this exists: the exported SVG is a standalone document that asked for
// `font-family: 'Outfit'` while the face itself arrived over a <link> to Google
// Fonts in render.html — which `captureSvg` neither inlines nor can inline (a
// cross-origin sheet's `cssRules` throws). Any viewer without Outfit installed
// therefore substituted a fallback, and since every box in the diagram is sized
// from the baked Outfit metrics (generate_font_metrics.js), substituted text
// does not fit the geometry it was measured for. The PNG never showed this:
// Chromium had fetched the webfont before it rasterized.
//
// Embedding also takes the network out of rendering. render.html loads over
// file://, so that <link> was a live fetch on every single render and nothing
// waited for it — the same lazily-loaded-webfont race that text measurement was
// moved off canvas to escape (INC-9), still present in the drawing layer.
//
// Output: src/vendor/outfit_faces.js, alongside the baked metrics table.
// Run automatically by `postinstall`.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUT = path.join(ROOT, 'src', 'vendor', 'outfit_faces.js');

// `--output <path>` writes elsewhere, which is how the drift test regenerates
// into a temp dir and compares without touching the committed file.
function parseOutput(argv) {
  const i = argv.indexOf('--output');
  if (i === -1) return DEFAULT_OUT;
  const value = argv[i + 1];
  if (!value) {
    console.error('--output requires a path.');
    process.exit(1);
  }
  return path.resolve(value);
}
const OUT = parseOutput(process.argv.slice(2));

// Every weight render.html can compute, and only those: an embedded face that
// nothing asks for is dead weight in every exported file. `bold` resolves to
// 700 and an unset `font-weight` to 400, so the set is wider than the literal
// declarations in the stylesheet. test/unit/font_faces_sync.test.js reads those
// declarations back out and fails if one of them is not covered here.
const WEIGHTS = [400, 500, 600, 700];

// woff2 only. Every browser that can open an SVG at all has supported it for
// years, and the woff fallback would double the size of every export for
// viewers that do not exist.
function fontPath(weight) {
  return path.join(ROOT, 'node_modules', '@fontsource', 'outfit', 'files', `outfit-latin-${weight}-normal.woff2`);
}

// Same reasoning as the metrics table: `@fontsource/outfit` is a devDependency,
// so its absence under `npm ci --omit=dev` is not an error when the generated
// file is already committed.
if (!WEIGHTS.every(w => fs.existsSync(fontPath(w)))) {
  if (fs.existsSync(DEFAULT_OUT)) {
    console.log('Outfit faces: @fontsource/outfit not installed; using the committed faces.');
    process.exit(0);
  }
  console.error(
    `Cannot generate ${path.relative(ROOT, DEFAULT_OUT)}: @fontsource/outfit is not installed and no ` +
    `committed faces file was found. Run a full \`npm install\` (without --omit=dev).`
  );
  process.exit(1);
}

console.log('Generating Outfit @font-face rules...');

// One rule per line, no comments and no incidental whitespace. The export
// inlines this stylesheet into XML, where a CSS comment containing a literal
// angle bracket ends the document early — base64 cannot produce `<`, `&` or
// `/*`, so keeping the generated text to rules alone keeps that whole class of
// breakage impossible rather than merely unlikely.
const rules = WEIGHTS.map((weight) => {
  const base64 = fs.readFileSync(fontPath(weight)).toString('base64');
  return `@font-face{font-family:'Outfit';font-style:normal;font-weight:${weight};` +
    `src:url(data:font/woff2;base64,${base64}) format('woff2')}`;
});

// A plain script, not a module: render.html loads it with a <script> tag,
// exactly like the elkjs bundle and the metrics table.
const banner = `// GENERATED by scripts/generate_font_faces.js — do not edit.
// Outfit (SIL Open Font License 1.1), baked as data: URLs so that a rendered
// diagram and an exported SVG both carry the face they were measured against.
`;
const body = `globalThis.NudgeOutfitFaces = ${JSON.stringify(rules.join('\n'))};\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, banner + body);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(1)} kB, ${WEIGHTS.length} weights)`);
